import { writeFile } from 'node:fs/promises';
import { chooseMove, candidates, HARD_BUDGET_MS } from '../src/ai.js';
import { canonicalOpening, transformOpeningIndex } from '../src/opening-book.js';

// Offline analysis using the same freestyle rules and full budget as Hard.
// Cover each distinct second black move within two cells of the centre, then
// the two highest-ranked black continuations for the third white response.
const entries = {};
function analyse(board) {
  const { key, symmetry } = canonicalOpening(board);
  if (entries[key]) return;
  const result = chooseMove(board, 'hard', { openingBook: false });
  entries[key] = {
    depth: result.depth,
    candidates: result.candidates.map(c => [transformOpeningIndex(c.index, symmetry), c.score]),
  };
  console.log(`${Object.keys(entries).length}: ${key} depth=${result.depth} elapsed=${result.elapsed}ms`);
  return result.index;
}
const first = Array(225).fill(0);
first[112] = 1;
const reply = analyse(first);
first[reply] = 2;
const positions = [], seen = new Set();
for (let y = 5; y <= 9; y++) for (let x = 5; x <= 9; x++) {
  const index = y * 15 + x;
  if (first[index]) continue;
  const board = [...first]; board[index] = 1;
  const { key } = canonicalOpening(board);
  if (!seen.has(key)) { seen.add(key); positions.push(board); }
}
for (const board of positions) {
  const move = analyse(board);
  board[move] = 2;
  for (const human of candidates(board, 1, 2)) {
    const continuation = [...board]; continuation[human.index] = 1;
    analyse(continuation);
  }
}
const sorted = Object.fromEntries(Object.entries(entries).sort(([a], [b]) => a.localeCompare(b)));
const contents = `// Generated by scripts/generate-opening-book.mjs. Do not edit entries by hand.\n// Freestyle 15×15; ${HARD_BUDGET_MS}ms analysis per position; ${Object.keys(entries).length} canonical positions.\nexport const openingBook = ${JSON.stringify(sorted, null, 2)};\n`;
await writeFile(new URL('../src/opening-book-data.js', import.meta.url), contents);
console.log(`Saved ${Object.keys(entries).length} canonical positions.`);
